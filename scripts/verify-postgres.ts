import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import { performance } from 'node:perf_hooks';
import { authenticate, login, logout, register, sessionCookie } from '../src/lib/auth';
import { closeDatabase, getWorkspace, nearbyPropertyIds, readDocument, transaction } from '../src/lib/db';
import { calculateCma, simulatePricing } from '../src/lib/analytics';
import { answerFromEvidence } from '../src/lib/assistant';
import { executeAction, uploadDocument, verifyAudit } from '../src/lib/service';
import { GET as reportGet } from '../src/app/api/report/route';

/** Opt-in integration acceptance. Never runs against SQLite or an arbitrary existing database. */
const run = randomUUID();
const emails = [0, 1].map(index => `postgres-acceptance-${run}-${index}@example.invalid`);
const checks: { name: string; passed: boolean; milliseconds: number }[] = [];
let cleanupPassed = true;
let started = false;

async function check(name: string, callback: () => Promise<void>) {
  const before = performance.now();
  try {
    await callback();
    checks.push({ name, passed: true, milliseconds: Math.round(performance.now() - before) });
  } catch (error) {
    checks.push({ name, passed: false, milliseconds: Math.round(performance.now() - before) });
    throw error;
  }
}

const request = (token: string, path = '/api/workspace') =>
  new Request(`https://ascent.example.invalid${path}`, { headers: { cookie: sessionCookie(token) } });

async function cleanup() {
  // Only the exact unguessable emails generated by this run are eligible for removal.
  for (const email of emails) {
    const users = await transaction(null, tx =>
      tx.query<{ id: string; tenant_id: string }>('SELECT id,tenant_id FROM users WHERE email=$1', [email]),
    );
    for (const user of users)
      await transaction(user.tenant_id, async tx => {
        await tx.query('DELETE FROM documents WHERE tenant_id=$1', [user.tenant_id]);
        await tx.query('DELETE FROM property_locations WHERE tenant_id=$1', [user.tenant_id]);
        await tx.query('DELETE FROM workspaces WHERE tenant_id=$1', [user.tenant_id]);
        await tx.query('DELETE FROM users WHERE id=$1 AND email=$2', [user.id, email]);
        await tx.query('DELETE FROM tenants WHERE id=$1', [user.tenant_id]);
      });
  }
}

async function main() {
  const url = new URL(process.env.DATABASE_URL || '');
  const expected = process.argv.find(arg => arg.startsWith('--database='))?.slice('--database='.length);
  assert.ok(
    expected && /^ascent(?:_[a-z0-9]+)*$/.test(expected),
    'Pass --database=ascent for a dedicated Ascent database.',
  );
  assert.ok(['postgres:', 'postgresql:'].includes(url.protocol));
  assert.equal(
    decodeURIComponent(url.pathname.slice(1)),
    expected,
    'Connection must match the explicitly selected Ascent database.',
  );
  assert.equal(
    Buffer.from(process.env.APP_ENCRYPTION_KEY || '', 'base64').length,
    32,
    'Configure the stable document encryption key first.',
  );
  Object.assign(process.env, { NODE_ENV: 'production' });

  await check('restricted runtime role, forced RLS, migrations and PostGIS', async () => {
    await transaction(null, async tx => {
      const rows = await tx.query<{
        database_name: string;
        can_create_role: boolean;
        can_create_database: boolean;
        can_create_schema: boolean;
        can_create_objects: boolean;
      }>(`SELECT current_database() AS database_name, rolcreaterole AS can_create_role,
        rolcreatedb AS can_create_database,
        has_database_privilege(current_user,current_database(),'CREATE') AS can_create_schema,
        has_schema_privilege(current_user,current_schema(),'CREATE') AS can_create_objects
        FROM pg_roles WHERE rolname=current_user`);
      assert.equal(rows[0].database_name, expected);
      assert.equal(rows[0].can_create_role, false);
      assert.equal(rows[0].can_create_database, false);
      assert.equal(rows[0].can_create_schema, false);
      assert.equal(rows[0].can_create_objects, false);
      const owners = await tx.query(`SELECT relname FROM pg_class
        WHERE relnamespace=current_schema()::regnamespace AND relkind='r'
        AND pg_has_role(current_user,relowner,'MEMBER')`);
      assert.equal(owners.length, 0, 'Runtime must not own or be able to assume ownership of any application table.');
      const extensions = await tx.query("SELECT extname FROM pg_extension WHERE extname='postgis'");
      assert.equal(extensions.length, 1);
      // Runtime deliberately has no access to the administrator's migration ledger.
      const tables = await tx.query(
        "SELECT 1 FROM pg_class WHERE relname='ascent_migrations' AND relnamespace=current_schema()::regnamespace",
      );
      assert.equal(tables.length, 1);
    });
  });

  started = true;
  const password = randomBytes(32).toString('base64url');
  const accounts: Awaited<ReturnType<typeof register>>[] = [];
  await check('instant registration and session authentication', async () => {
    for (const email of emails)
      accounts.push(await register({ seed: 'demo', name: 'Synthetic PostgreSQL acceptance', email, password }));
    assert.equal((await authenticate(request(accounts[0].token))).tenantId, accounts[0].user.tenantId);
    const loggedIn = await login(emails[0], password);
    assert.equal(loggedIn.user.id, accounts[0].user.id);
    await logout(request(loggedIn.token));
    await assert.rejects(authenticate(request(loggedIn.token)), /expired/);
  });
  const [a, b] = accounts;

  await check('database RLS denies cross-tenant reads, writes and unscoped access', async () => {
    assert.equal((await transaction(null, tx => tx.query('SELECT tenant_id FROM workspaces'))).length, 0);
    await transaction(a.user.tenantId, async tx => {
      const rows = await tx.query<{ tenant_id: string }>('SELECT tenant_id FROM workspaces');
      assert.deepEqual(
        rows.map(row => row.tenant_id),
        [a.user.tenantId],
      );
      assert.equal(
        (
          await tx.query('UPDATE workspaces SET version=version+1 WHERE tenant_id=$1 RETURNING tenant_id', [
            b.user.tenantId,
          ])
        ).length,
        0,
      );
    });
    await assert.rejects(
      transaction(a.user.tenantId, tx =>
        tx.query('INSERT INTO documents(id,tenant_id,data,encrypted,created_at) VALUES($1,$2,$3,1,$4)', [
          randomUUID(),
          b.user.tenantId,
          Buffer.from('synthetic forbidden write'),
          new Date().toISOString(),
        ]),
      ),
      (error: unknown) => (error as { code?: string }).code === '42501',
    );
    // Reusing a pooled connection must not retain the previous transaction's tenant.
    assert.equal((await transaction(null, tx => tx.query('SELECT tenant_id FROM workspaces'))).length, 0);
  });

  await check('PostGIS geographic search and durable concurrent client edits', async () => {
    const workspace = await getWorkspace(a.user.tenantId);
    const property = workspace.properties[0];
    assert.ok((await nearbyPropertyIds(a.user.tenantId, property.lat, property.lng, 1))?.includes(property.id));
    await Promise.all(
      ['first synthetic note', 'second synthetic note'].map(note =>
        executeAction(a.user, { type: 'addClientNote', id: workspace.clients[0].id, note }),
      ),
    );
    const updated = await getWorkspace(a.user.tenantId);
    assert.ok(updated.clients[0].timeline.some(item => item.note === 'first synthetic note'));
    assert.ok(updated.clients[0].timeline.some(item => item.note === 'second synthetic note'));
    assert.equal(JSON.stringify((await getWorkspace(b.user.tenantId)).clients).includes('first synthetic note'), false);
    assert.ok(verifyAudit(updated), 'Audit hashes must survive jsonb serialization.');
  });

  await check('encrypted document bytes, human-reviewed dates and tenant privacy', async () => {
    const workspace = await getWorkspace(a.user.tenantId);
    const bytes = Buffer.from('SYNTHETIC TEST. Inspection is due 2026-11-22.');
    const uploaded = await uploadDocument(a.user, workspace.transactions[0].id, {
      name: 'synthetic-postgres-acceptance.txt',
      type: 'text/plain',
      bytes,
    });
    const document = uploaded.result;
    assert.deepEqual(await readDocument(a.user.tenantId, document.id), bytes);
    assert.equal(await readDocument(b.user.tenantId, document.id), null);
    const rows = await transaction(a.user.tenantId, tx =>
      tx.query<{ encrypted: number; data: Buffer }>('SELECT encrypted,data FROM documents WHERE id=$1', [document.id]),
    );
    assert.equal(rows[0].encrypted, 1);
    assert.equal(rows[0].data.includes(bytes), false);
    assert.ok(document.extractedDates.length > 0);
    assert.ok(document.extractedDates.every(date => !date.approved));
  });

  await check('saved CMA reproduces from jsonb, scenarios, evidence assistant and report export', async () => {
    const workspace = await getWorkspace(a.user.tenantId);
    await executeAction(a.user, {
      type: 'saveCma',
      propertyId: workspace.properties[0].id,
      name: 'Synthetic PostgreSQL acceptance CMA',
    });
    const updated = await getWorkspace(a.user.tenantId);
    const cma = updated.cmas.find(record => record.name === 'Synthetic PostgreSQL acceptance CMA')!;
    assert.ok(cma?.result.inputSnapshot);
    const snapshot = cma.result.inputSnapshot;
    const recomputed = calculateCma(snapshot.subject, snapshot.candidates, cma.result.assumptions, cma.result.asOf);
    assert.equal(recomputed.calculationHash, cma.result.calculationHash);
    assert.equal(recomputed.estimate, cma.result.estimate);
    assert.ok(Number.isFinite(simulatePricing(cma.result, cma.result.strategies.moderate).listPrice));
    const answer = answerFromEvidence(updated, 'Explain this CMA and its uncertainty', {
      cmaId: cma.id,
      propertyId: cma.propertyId,
    });
    assert.equal(answer.mode, 'evidence');
    assert.ok(answer.citations.length > 0);
    const report = await reportGet(request(a.token, `/api/report?cmaId=${encodeURIComponent(cma.id)}`));
    assert.equal(report.status, 200);
    assert.match(await report.text(), /synthetic/i);
    const forbidden = await reportGet(request(b.token, `/api/report?cmaId=${encodeURIComponent(cma.id)}`));
    assert.equal(forbidden.status, 404);
  });
}

main()
  .catch(() => {
    process.exitCode = 1;
  })
  .finally(async () => {
    if (started) {
      try {
        await cleanup();
      } catch {
        cleanupPassed = false;
        process.exitCode = 1;
      }
    }
    await closeDatabase();
    console.log(
      JSON.stringify(
        {
          verified: checks.length === 6 && checks.every(check => check.passed) && cleanupPassed,
          checks,
          cleanup: started
            ? cleanupPassed
              ? 'passed'
              : 'failed; inspect this run’s synthetic accounts'
            : 'not-needed',
          note: 'Dedicated PostgreSQL only. Synthetic records; no paid provider calls or existing customer data copied. Failure details are withheld to protect credentials.',
        },
        null,
        2,
      ),
    );
  });
